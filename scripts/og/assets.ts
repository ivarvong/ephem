// Render ephem's two static preview images with glyph and write packages/worker/src/og-png.generated.ts:
//   apple-touch-icon (180×180, src/og.ts iconSpec) and the fallback card (src/og.ts fallbackSpec, 600×315: dpr 0.5).
//   node --experimental-strip-types scripts/og/assets.ts [--glyph-lib <glyph clone>]
// Default: POST to https://glyph.ivar.workers.dev (fonts from prod /assets/<sha>/…). --glyph-lib renders with a local clone of
// github.com/ivarvong/glyph (after its `node scripts/fetch.js --runtime`), the fonts read from src/din.ts: no network, so it
// works before the font routes are deployed. Same library, same bytes either way.
import { writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { iconSpec, fallbackSpec } from "../../packages/worker/src/og.ts"
import { OG_FONTS } from "../../packages/worker/src/og-fonts.ts"
import { DIN_BOLD_B64, DIN_REGULAR_B64 } from "../../packages/worker/src/din.ts"

const i = process.argv.indexOf("--glyph-lib"),
  lib = i > 0 ? resolve(process.argv[i + 1]!) : null
const render = async (spec: unknown, dpr: number): Promise<Buffer> => {
  const body = JSON.stringify(spec)
  if (!lib) {
    const r = await fetch(`https://glyph.ivar.workers.dev/render?dpr=${dpr}`, { method: "POST", body })
    if (!r.ok) throw new Error(`glyph ${r.status}: ${await r.text()}`)
    return Buffer.from(await r.arrayBuffer())
  }
  const { createRenderer } = await import(`${lib}/worker/src/app.js`),
    { NOOP_TRACER } = await import(`${lib}/otel-compact/src/trace.js`)
  const fonts: Record<string, string> = {
    "ephem-din-regular.woff2": DIN_REGULAR_B64,
    "ephem-din-bold.woff2": DIN_BOLD_B64,
  }
  const pf = {
    fetch: async (u: string) => new Response(Buffer.from(fonts[String(u).split("/").pop()!]!, "base64")),
    cached: null,
    bucket: null,
    specs: null,
    defer: () => {},
    tracer: NOOP_TRACER,
  }
  const r: Response = await createRenderer().handle(
    new Request(`https://glyph.local/render?dpr=${dpr}`, { method: "POST", body }),
    pf,
  )
  if (r.status !== 200) throw new Error(`glyph ${r.status}: ${await r.text()}`)
  return Buffer.from(await r.arrayBuffer())
}
const icon = await render(iconSpec(), 1),
  fallback = await render(fallbackSpec(OG_FONTS), 0.5)
const out = resolve(import.meta.dirname, "../../packages/worker/src/og-png.generated.ts")
writeFileSync(
  out,
  `// GENERATED by scripts/og/assets.ts from src/og.ts iconSpec / fallbackSpec, rendered by glyph. Do not edit.
export const ICON_PNG_B64 = "${icon.toString("base64")}"   // 180×180, ${icon.length} B
export const FALLBACK_PNG_B64 = "${fallback.toString("base64")}"   // 600×315, ${fallback.length} B
`,
)
console.log(out, "icon", icon.length, "B, fallback", fallback.length, "B")
