// The homepage's in-browser compute: @ephem/core's position, track and day (packages/core/src/browser.ts) bundled by esbuild
// into one IIFE (global __ephemCore), written to packages/worker/src/sky-core.generated.ts with its sha256 and its module list.
// The front door serves it at /assets/<sha256[0:16]>/ephem-sky.js, immutable (src/sky-assets.ts).
//   node --experimental-strip-types scripts/build-sky-core.ts          # (re)write the generated module
//   node --experimental-strip-types scripts/build-sky-core.ts --check  # exit 1 if it is stale (the gate's test does the same)
// Any change to the core code these functions run changes the bundle, so it must be rebuilt in the same commit (the page then
// runs the same code as the API by construction; the test fails otherwise).
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"
import { build } from "esbuild"

const ROOT = join(import.meta.dirname, "..")
export const ENTRY = join(ROOT, "packages/core/src/browser.ts")
export const OUT = join(ROOT, "packages/worker/src/sky-core.generated.ts")

export const buildSkyCore = async () => {
  const r = await build({ entryPoints: [ENTRY], bundle: true, minify: true, format: "iife", globalName: "__ephemCore", target: "es2020",
    write: false, metafile: true, legalComments: "none", charset: "utf8", logLevel: "silent", absWorkingDir: ROOT })
  const js = r.outputFiles[0]!.text.trimEnd() + "\n"
  const inputs = Object.keys(r.metafile.inputs).map(p => relative(ROOT, join(ROOT, p))).toSorted()
  return { js, sha256: createHash("sha256").update(js).digest("hex"), inputs }
}

export const generated = (b: Awaited<ReturnType<typeof buildSkyCore>>) =>
  `// GENERATED by scripts/build-sky-core.ts from packages/core/src/browser.ts (esbuild, minified IIFE, global __ephemCore); do not edit.\n` +
  `// packages/worker/test/sky-core.test.ts rebuilds it and fails when it is stale. Served at /assets/<sha16>/ephem-sky.js (src/sky-assets.ts).\n` +
  `export const SKY_CORE_SHA256 = ${JSON.stringify(b.sha256)}\n` +
  `export const SKY_CORE_INPUTS: ReadonlyArray<string> = ${JSON.stringify(b.inputs)}\n` +
  `export const SKY_CORE_JS = ${JSON.stringify(b.js)}\n`

if (import.meta.main) {
  const b = await buildSkyCore(), text = generated(b)
  if (process.argv.includes("--check")) {
    const cur = readFileSync(OUT, "utf8")
    if (cur !== text) { console.error(`${relative(ROOT, OUT)} is stale: run node --experimental-strip-types scripts/build-sky-core.ts`); process.exit(1) }
    console.log(`up to date: ${b.js.length} B, sha256 ${b.sha256.slice(0, 16)}`)
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote ${relative(ROOT, OUT)}: ${b.js.length} B, sha256 ${b.sha256.slice(0, 16)}, ${b.inputs.length} modules: ${b.inputs.map(p => p.split("/").pop()).join(" ")}`)
  }
}
