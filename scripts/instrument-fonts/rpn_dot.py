for ch, rows in G.items():   # every glyph fits the 8-dot line: 7 rows above the baseline + 1 descender row, 5 columns
    assert len(rows) <= 8 and all(len(r) == 5 for r in rows), ch
U = 100      # one dot
INK = 100    # a whole dot: glyph edges land on the dot grid, so at an integer device-pixel dot they are exactly on pixels.
             # The seam between dots is drawn over the glass by the page (src/instrument.ts), one device pixel wide.

def glyph(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        for c, v in enumerate(row):
            if v != '#':
                continue
            x0 = c * U + (U - INK) // 2
            y0 = (6 - r) * U + (U - INK) // 2
            pen.moveTo((x0, y0)); pen.lineTo((x0, y0 + INK)); pen.lineTo((x0 + INK, y0 + INK)); pen.lineTo((x0 + INK, y0)); pen.closePath()
    return pen.glyph()

names = {ch: ('space' if ch == ' ' else 'nbspace' if ch == ' ' else 'uni%04X' % ord(ch)) for ch in G}
order = ['.notdef'] + [names[c] for c in G]
glyphs = {'.notdef': glyph(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'])}
for ch, rows in G.items():
    glyphs[names[ch]] = glyph(rows)
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap({ord(c): names[c] for c in G})
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (600, 0) for n in order})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({'familyName': 'RPN Dot', 'styleName': 'Regular', 'uniqueFontIdentifier': 'RPN Dot Regular 1.0',
                   'fullName': 'RPN Dot Regular', 'psName': 'RPNDot-Regular', 'version': 'Version 1.000',
                   'copyright': 'Original design for the RPN Instrument design system, 2026.',
                   'licenseDescription': 'SIL Open Font License 1.1', 'licenseInfoURL': 'https://openfontlicense.org'})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200,
            sxHeight=500, sCapHeight=700, fsType=0, achVendID='RPN ', xAvgCharWidth=600)
fb.font['OS/2'].panose.bProportion = 9
fb.setupPost(isFixedPitch=1)
fb.font.flavor = 'woff2'
fb.save(sys.argv[1])
