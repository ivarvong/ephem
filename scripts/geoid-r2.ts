// EGM96 geoid bands → R2 (bucket ephem-geoid; never ephem-de440). One object, sha-addressed, all 46 bands back to back.
//   node --experimental-strip-types scripts/geoid-r2.ts manifest   # (re)write packages/core/src/egm96-bands.ts from egm96-grid.ts
//   node --experimental-strip-types scripts/geoid-r2.ts upload     # put the object unless the bucket already has it (idempotent)
//   node --experimental-strip-types scripts/geoid-r2.ts verify     # read the object back and compare every byte
// The key carries the object's sha256 (egm96-30/<sha16>.bin), so a different grid can never overwrite or alias an old one;
// BlockStore range-reads one band per request (src/geoid.ts serveGeoid) and checks each band's sha before it is cached.
import { createHash } from "node:crypto"
import { execFileSync } from "node:child_process"
import { mkdtempSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { EGM96_30 } from "../packages/core/src/egm96-grid.ts"
import { bundledGeoidBand, bundledGeoidObject } from "../packages/core/src/geoid-bundled.ts"

const BUCKET = "ephem-geoid"
const sha = (b: Uint8Array) => createHash("sha256").update(b).digest("hex")
const obj = bundledGeoidObject(), objSha = sha(obj)
const key = `egm96-30/${objSha.slice(0, 16)}.bin`
const cf = (...args: string[]): Buffer => execFileSync("cf", args, { stdio: ["ignore", "pipe", "pipe"], maxBuffer: 1 << 26 })

const cmd = process.argv[2]
if (cmd === "manifest") {
  let off = 0
  const bands = EGM96_30.bands.map((_, b) => { const x = bundledGeoidBand(b), e = [off, x.length, sha(x).slice(0, 16)] as const; off += x.length; return e })
  const out = `// GENERATED by scripts/geoid-r2.ts manifest from egm96-grid.ts, do not edit. The EGM96 30′ grid's 46 bands of 8 rows as one
// R2 object (bucket ephem-geoid, key = KEY): per band [byte offset, byte length, sha256 prefix]. The Worker bundles only this.
export const EGM96_BANDS = {
  rows: ${EGM96_30.rows}, cols: ${EGM96_30.cols}, stepDeg: ${EGM96_30.stepDeg}, bandRows: ${EGM96_30.bandRows},
  sha256: "${objSha}", bytes: ${obj.length}, key: "${key}",
  bands: [
${bands.map(b => `    [${b[0]}, ${b[1]}, "${b[2]}"],`).join("\n")}
  ] as ReadonlyArray<readonly [offset: number, length: number, sha16: string]>,
} as const
`
  writeFileSync(new URL("../packages/core/src/egm96-bands.ts", import.meta.url), out)
  console.log(`wrote egm96-bands.ts: ${bands.length} bands, object ${obj.length} B, sha256 ${objSha}, key ${key}`)
} else if (cmd === "upload" || cmd === "verify") {
  const dir = mkdtempSync(join(tmpdir(), "geoid-"))
  // `cf r2 objects get` writes the raw bytes to stdout; a missing key exits non-zero
  const fetchBack = () => { try { return new Uint8Array(cf("r2", "objects", "get", key, "--bucket-name", BUCKET)) } catch { return undefined } }
  let back = fetchBack()
  if (cmd === "upload") {
    if (back && sha(back) === objSha) console.log(`${BUCKET}/${key} already present (${back.length} B, sha256 ok): nothing to do`)
    else {
      const file = join(dir, "obj.bin"); writeFileSync(file, obj)
      cf("r2", "objects", "put", key, "--bucket-name", BUCKET, "--content-type", "application/octet-stream", "--body", `@${file}`)
      back = fetchBack()
      console.log(`put ${BUCKET}/${key}: ${obj.length} B`)
    }
  }
  if (!back || sha(back) !== objSha) { console.error(`FAIL: ${BUCKET}/${key} ${back ? `sha256 ${sha(back)} ≠ ${objSha}` : "missing"}`); process.exit(1) }
  console.log(`verified ${BUCKET}/${key}: ${back.length} B, sha256 ${objSha}`)
} else { console.error("usage: geoid-r2.ts manifest|upload|verify"); process.exit(2) }
