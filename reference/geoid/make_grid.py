#!/usr/bin/env python3
"""Build packages/core/src/egm96-grid.ts: EGM96 geoid undulations from NGA's official 15′ grid, subsampled to 30′.

    reference/geoid/fetch.sh                      # NGA zip (WW15MGH.GRD + NGA's test points), PROJ's GeoTIFF; SHA-256 pinned
    python3 reference/geoid/make_grid.py          # writes the TS module and prints sizes + subsampling error stats

Source: NGA, "EGM96 15-minute interpolation grid" (earth-info.nga.mil, file egm-96interpolation: WW15MGH.GRD, 721 × 1441 point
values, 90°N→90°S, 0°E→360°E). Every 2nd row/column is kept (361 × 720, 0..359.5°E), rounded to the centimetre (≤ 0.005 m),
stored as the residual of the planar predictor (left + above − above-left; first row/column: the previous node), zigzag
LEB128 varints, base64. Core decodes it once and interpolates bilinearly between the 30′ nodes.
"""
import base64, gzip, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
GRD = os.path.join(HERE, "inputs", "WW15MGH.GRD")
OUT = os.path.join(ROOT, "packages/core/src/egm96-grid.ts")
STEP = 2   # 15′ × 2 = 30′

v = np.array(open(GRD).read().split(), dtype=float)
assert list(v[:6]) == [-90, 90, 0, 360, 0.25, 0.25], v[:6]
G = v[6:].reshape(721, 1441)
S = G[::STEP, :-1:STEP]                    # 361 × 720
assert S.shape == (361, 720)
q = np.round(S * 100).astype(np.int64)
pred = np.zeros_like(q); pred[0, 1:] = q[0, :-1]; pred[1:, 0] = q[:-1, 0]; pred[1:, 1:] = q[:-1, 1:] + q[1:, :-1] - q[:-1, :-1]
out = bytearray()
for v in (q - pred).ravel().tolist():
    z = (v << 1) ^ (v >> 63)
    while z >= 0x80: out.append((z & 0x7F) | 0x80); z >>= 7
    out.append(z)
b64 = base64.b64encode(bytes(out)).decode()
src = (f"// GENERATED by reference/geoid/make_grid.py, do not edit. EGM96 geoid undulation N (cm), NGA WW15MGH.GRD 15′ grid\n"
       f"// subsampled to 30′: 361 rows (90°N → 90°S) × 720 columns (0°E → 359.5°E); planar-predictor residuals, zigzag varints, base64.\n"
       f"export const EGM96_30 = {{ rows: 361, cols: 720, stepDeg: 0.5, data: \"{b64}\" }} as const\n")
open(OUT, "w").write(src)
print(f"wrote {OUT}: {len(src)} bytes, gzip {len(gzip.compress(src.encode(), 9))} bytes; nodes {q.size}")
np.save(os.path.join(HERE, "inputs", "nodes30_cm.npy"), q)   # for the decode test
